// coding-standard: maintained
/**
 * Generates `lib/help/content.generated.ts` from `docs/help/en/*.md`.
 *
 * Why generate instead of reading the files at runtime
 * ----------------------------------------------------
 * The app ships as a standalone Docker image built from `.next/`; `docs/` is not in it, so a
 * runtime `fs.readFile` of a help page would work in dev and 404 in production. Baking the content
 * into a module removes that class of bug entirely, and makes the drawer open with no fetch — which
 * matters, because the person opening it is mid-task with a customer waiting.
 *
 * The body stays raw Markdown. `lib/storefront-markdown.ts` parses it into a block model at render
 * time (dependency-free, no HTML strings), so nothing here needs a Markdown parser and the help
 * drawer cannot become an HTML-injection surface.
 *
 * Committed to git, like `types/api-generated.ts`, so a fresh checkout type-checks before anything
 * has been run. Regenerated by `predev`/`prebuild`, so it cannot silently drift from the Markdown.
 *
 * Usage:  pnpm help:build
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { parseFrontmatter } from "./help/frontmatter.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(SCRIPT_DIR, "..");
const HELP_DIR = path.join(REPO_ROOT, "docs", "help");
const OUT_FILE = path.join(REPO_ROOT, "lib", "help", "content.generated.ts");

/** English is the source; every other locale is a translation of it and may lag behind. */
const LOCALES = ["en", "bn"];

/**
 * `[text](./receive-stock.md)` → `[text](/help/receive-stock)`.
 *
 * Relative `.md` links are what make the pages navigable as files (and what `docs:verify` checks),
 * but they are meaningless to the browser. Rewriting them to real in-app URLs means the same link
 * works as a file on disk, as a drawer navigation, and as a shareable link support staff can send.
 */
const rewriteLinks = (body) => body.replace(/\]\(\.\/([\w-]+)\.md\)/g, "](/help/$1)");

/** The drawer and page render the title from frontmatter, so a body H1 would show it twice. */
const stripLeadingH1 = (body) => body.replace(/^\s*#\s+.*(\r?\n)+/, "");

function readLocale(locale) {
  const dir = path.join(HELP_DIR, locale);
  if (!fs.existsSync(dir)) return [];

  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith(".md"))
    .map((file) => {
      // Keep the committed module byte-stable across Windows and Unix. Without
      // normalizing here, CRLF source files rewrite every generated body string
      // even when one help paragraph changed.
      const source = fs
        .readFileSync(path.join(dir, file), "utf8")
        .replace(/\r\n/g, "\n");
      const parsed = parseFrontmatter(source);
      if (!parsed) {
        throw new Error(`docs/help/${locale}/${file}: missing frontmatter — run pnpm help:verify`);
      }

      const { data, body } = parsed;
      return {
        slug: data.slug ?? path.basename(file, ".md"),
        title: data.title ?? "",
        summary: data.summary ?? "",
        order: Number(data.order ?? 999),
        coversRoutes: data.covers_routes ?? [],
        features: data.features ?? [],
        // Optional: a hosted walkthrough URL for this page. The videos this
        // was written for already exist (recorded per guide) but sat outside
        // the drawer entirely — a merchant reaching "?" mid-task saw text
        // only, never the recording that shows the exact same screen.
        videoUrl: data.video ?? null,
        body: stripLeadingH1(rewriteLinks(body)).trim(),
      };
    })
    .sort((a, b) => a.order - b.order);
}

const byLocale = Object.fromEntries(LOCALES.map((locale) => [locale, readLocale(locale)]));

const output = `// coding-standard: maintained
// GENERATED by scripts/build-help-content.mjs from docs/help/<locale>/*.md — DO NOT EDIT.
// Edit the Markdown, then run \`pnpm help:build\`.

export interface HelpPage {
  slug: string;
  title: string;
  summary: string;
  order: number;
  /** App routes this page documents — drives the contextual "?" in the header. */
  coversRoutes: string[];
  /** Feature flags the page's subject depends on. */
  features: string[];
  /** Hosted walkthrough video for this page, from frontmatter \`video:\`. Absent for most pages. */
  videoUrl: string | null;
  /** Raw Markdown, rendered via lib/storefront-markdown.ts. */
  body: string;
}

export type HelpLocale = ${LOCALES.map((l) => `"${l}"`).join(" | ")};

/**
 * Pages per locale. A locale may be incomplete — a reader on it falls back to English for any page
 * not yet translated, which is better than showing them nothing.
 */
export const helpPagesByLocale: Record<HelpLocale, HelpPage[]> = ${JSON.stringify(byLocale, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output);

const counts = LOCALES.map((l) => `${l}: ${byLocale[l].length}`).join(", ");
console.log(`help:build — ${counts} → lib/help/content.generated.ts`);

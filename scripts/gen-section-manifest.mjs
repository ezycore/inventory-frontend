// coding-standard: maintained
/**
 * Writes the backend's section manifest from the frontend's section specs.
 *
 *   node --experimental-strip-types --no-warnings scripts/gen-section-manifest.mjs           # write
 *   node --experimental-strip-types --no-warnings scripts/gen-section-manifest.mjs --check   # CI gate
 *
 * Why it exists
 * -------------
 * The Storefront Builder's vocabulary is owned by the frontend
 * (`lib/storefront-builder/section-specs.ts`) and enforced by the backend, which
 * refuses any section setting its manifest does not describe. Two hand-kept
 * copies would drift the way hand-written API types did: the editor would offer
 * a setting the backend rejects on save, or the backend would accept one the
 * renderer ignores. This is `verify:api-types` in the other direction — the
 * frontend is the source, the backend the generated side.
 *
 * The output is the backend file `src/constants/storefront-section-manifest.ts`:
 * the body of `lib/storefront-builder/field-specs.ts` copied verbatim (one set of
 * types for both repos) followed by the manifest literal. A `.ts` module rather
 * than JSON because the backend's `tsc` does not copy `.json` into `dist/`.
 *
 * Like `verify-api-types.mjs`, `--check` skips rather than fails when the
 * backend repo is not checked out beside this one.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const TARGET = "../inventory-backend/src/constants/storefront-section-manifest.ts";
const SPECS_PATH = "lib/storefront-builder/section-specs.ts";
const FIELD_SPECS_PATH = "lib/storefront-builder/field-specs.ts";
const REGEN_CMD = "pnpm gen:section-manifest";
const MARKER = "// coding-standard: maintained";

const check = process.argv.includes("--check");

// The specs are TypeScript, loaded with Node's own type stripping — on by
// default from Node 23.6, behind a flag on 22.6+, absent before. The flag is
// added here rather than in package.json because an unknown flag makes Node
// exit before this file runs, and the PR workflow still uses Node 20.
if (!process.features?.typescript) {
  const [major, minor] = process.versions.node.split(".").map(Number);
  if (major < 22 || (major === 22 && minor < 6)) {
    const message = `⚠ Section manifest needs Node 22.6+ (this is ${process.version}); see .nvmrc.`;
    if (check) {
      console.warn(`${message} Skipping the check.`);
      process.exit(0);
    }
    console.error(message);
    process.exit(1);
  }
  const rerun = spawnSync(
    process.execPath,
    ["--experimental-strip-types", "--no-warnings", fileURLToPath(import.meta.url), ...process.argv.slice(2)],
    { stdio: "inherit" },
  );
  process.exit(rerun.status ?? 1);
}

if (!existsSync("../inventory-backend/src/constants")) {
  const message =
    "⚠ Skipping section manifest: inventory-backend not found beside this repo.";
  if (check) {
    console.warn(message);
    process.exit(0);
  }
  console.error(message);
  process.exit(1);
}

const { SECTION_SPECS, SECTION_MANIFEST_VERSION } = await import(
  new URL(`../${SPECS_PATH}`, import.meta.url)
);

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A deterministic TypeScript literal: 2-space indent, trailing commas, bare keys where legal. */
const literal = (value, depth) => {
  if (Array.isArray(value)) return `[${value.map((item) => literal(item, depth + 1)).join(", ")}]`;
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    const inner = "  ".repeat(depth + 1);
    const lines = entries.map(
      ([key, item]) =>
        `${inner}${IDENTIFIER.test(key) ? key : JSON.stringify(key)}: ${literal(item, depth + 1)},`,
    );
    return `{\n${lines.join("\n")}\n${"  ".repeat(depth)}}`;
  }
  return JSON.stringify(value);
};

const fieldSpecsBody = readFileSync(FIELD_SPECS_PATH, "utf8")
  .replace(/\r\n/g, "\n")
  .replace(`${MARKER}\n`, "")
  .trimEnd();

const manifest = {
  version: SECTION_MANIFEST_VERSION,
  source: `inventory-frontend/${SPECS_PATH}`,
  sections: SECTION_SPECS,
};

const output = `${MARKER}
// GENERATED by inventory-frontend/scripts/gen-section-manifest.mjs — do not edit.
// Change lib/storefront-builder/section-specs.ts in the frontend, then run \`${REGEN_CMD}\` there.
/**
 * The Storefront Builder's SECTION MANIFEST — which section types exist, where
 * each may be placed, and the exact shape of its settings.
 *
 * The backend never decides what a section looks like; it only refuses what this
 * manifest does not describe, because a page config is merchant-written JSON
 * that ends up in every shopper's HTML. Read by
 * \`src/utils/storefront-section-validation.ts\`.
 */

${fieldSpecsBody}

export const SECTION_MANIFEST: SectionManifest = ${literal(manifest, 0)};
`;

const normalize = (text) => text.replace(/\r\n/g, "\n");
const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";

if (check) {
  if (normalize(current) !== output) {
    console.error(
      `✖ ${TARGET} is out of date with ${SPECS_PATH}.\n` +
        "  The frontend's section vocabulary changed but the backend manifest was not regenerated,\n" +
        "  so the backend would validate saved pages against stale section settings.\n" +
        `  Fix:  ${REGEN_CMD}   then commit the backend file.`,
    );
    process.exit(1);
  }
  console.log("✓ Backend section manifest matches the frontend section specs.");
} else {
  writeFileSync(TARGET, output);
  console.log(`✓ Wrote ${TARGET} (${Object.keys(SECTION_SPECS).length} sections).`);
}
